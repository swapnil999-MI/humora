/** One emoji category from assets/emoji.json (generated by scripts/gen-emoji.py). */
internal data class EmojiGroup(val name: String, val emojis: List<Pair<String, String>>)

internal object PulseEmojis {
    @Volatile private var cache: List<EmojiGroup>? = null
    private const val PREFS = "pulse_emoji"
    private const val RECENT = "recent"
    private const val RECENT_MAX = 32

    suspend fun load(context: Context): List<EmojiGroup> = cache ?: withContext(Dispatchers.IO) {
        val text = context.assets.open("emoji.json").bufferedReader().use { it.readText() }
        val arr = JSONArray(text)
        List(arr.length()) { i ->
            val g = arr.getJSONObject(i)
            val list = g.getJSONArray("emojis")
            EmojiGroup(g.getString("group"), List(list.length()) { j -> list.getJSONArray(j).let { it.getString(0) to it.getString(1) } })
        }.also { cache = it }
    }

    fun recent(context: Context): List<String> =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(RECENT, "")!!
            .split('\u0001').filter { it.isNotEmpty() }

    fun remember(context: Context, emoji: String) {
        val next = (listOf(emoji) + recent(context).filter { it != emoji }).take(RECENT_MAX)
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(RECENT, next.joinToString("\u0001")).apply()
    }
}

private val TAB_EMOJI = mapOf(
    "Recently used" to "🕘", "Smileys & Emotion" to "😀", "People & Body" to "👋", "Animals & Nature" to "🐻",
    "Food & Drink" to "🍔", "Travel & Places" to "🚗", "Activities" to "⚽", "Objects" to "💡", "Symbols" to "🔣", "Flags" to "🏳️",
)

/**
 * WhatsApp-style emoji picker with every Unicode emoji: category tabs, search and recently used.
 * [closeOnPick] is true for reactions (one pick) and false for typing (keep picking).
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun EmojiPickerSheet(
    onPick: (String) -> Unit,
    onDismiss: () -> Unit,
    closeOnPick: Boolean,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var groups by remember { mutableStateOf<List<EmojiGroup>?>(null) }
    val recent = remember { PulseEmojis.recent(context) }
    var query by remember { mutableStateOf("") }
    val gridState = rememberLazyGridState()

    LaunchedEffect(Unit) { groups = PulseEmojis.load(context) }

    val visible = remember(groups, query, recent) {
        val all = groups.orEmpty()
        val q = query.trim().lowercase()
        when {
            q.isNotEmpty() -> listOf(EmojiGroup("Search results", all.flatMap { g -> g.emojis.filter { it.second.contains(q) } }))
            recent.isNotEmpty() -> listOf(EmojiGroup("Recently used", recent.map { it to it })) + all
            else -> all
        }
    }
    // Grid index of each group's header, for the category tabs.
    val headerIndex = remember(visible) {
        var i = 0
        visible.associate { g -> (g.name to i).also { i += 1 + g.emojis.size } }
    }

    ModalBottomSheet(onDismissRequest = onDismiss, containerColor = Color(0xFF1F2C34)) {
        Column(Modifier.fillMaxWidth().height(440.dp)) {
            // Category tabs
            Row(Modifier.fillMaxWidth().padding(horizontal = 8.dp), horizontalArrangement = Arrangement.SpaceBetween) {
                visible.filter { query.isBlank() }.forEach { g ->
                    Text(
                        TAB_EMOJI[g.name] ?: "😀", fontSize = 20.sp,
                        modifier = Modifier.clip(RoundedCornerShape(8.dp)).clickable {
                            headerIndex[g.name]?.let { scope.launch { gridState.scrollToItem(it) } }
                        }.padding(6.dp)
                    )
                }
            }
            // Search
            Row(
                Modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 6.dp).clip(RoundedCornerShape(20.dp))
                    .background(Color(0xFF2A3942)).padding(horizontal = 12.dp, vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Icon(Icons.Default.Search, contentDescription = null, tint = Color(0xFF8696A0), modifier = Modifier.size(18.dp))
                Spacer(Modifier.width(8.dp))
                BasicTextField(
                    value = query, onValueChange = { query = it }, singleLine = true,
                    textStyle = TextStyle(color = TextPrimaryDark, fontSize = 14.sp), cursorBrush = SolidColor(Color(0xFF00A884)),
                    decorationBox = { inner -> if (query.isEmpty()) Text("Search emoji", color = Color(0xFF8696A0), fontSize = 14.sp); inner() },
                    modifier = Modifier.weight(1f)
                )
            }
            if (groups == null) {
                Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) { CircularProgressIndicator(color = Color(0xFF00A884)) }
            } else {
                LazyVerticalGrid(
                    columns = GridCells.Adaptive(46.dp),
                    state = gridState,
                    modifier = Modifier.fillMaxSize().padding(horizontal = 6.dp),
                ) {
                    visible.forEach { g ->
                        item(key = "h-${g.name}", span = { GridItemSpan(maxLineSpan) }) {
                            Text(
                                g.name.uppercase(), fontSize = 11.sp, fontWeight = FontWeight.SemiBold, color = Color(0xFF8696A0),
                                modifier = Modifier.padding(start = 6.dp, top = 10.dp, bottom = 4.dp)
                            )
                        }
                        items(g.emojis, key = { "${g.name}-${it.first}" }) { (emoji, _) ->
                            Box(
                                Modifier.aspectRatio(1f).clip(RoundedCornerShape(8.dp)).clickable {
                                    PulseEmojis.remember(context, emoji) // shown in "Recently used" next time
                                    onPick(emoji)
                                    if (closeOnPick) onDismiss()
                                },
                                contentAlignment = Alignment.Center
                            ) { Text(emoji, fontSize = 26.sp) }
                        }
                    }
                }
            }
        }
    }
}
